`timescale 1ns/1ps

module tb_alu_ai_enable;

    reg [31:0] A;
    reg [31:0] B;
    reg [31:0] C;
    reg        alu_en;
    reg [4:0]  alucontrol;
    reg [1:0]  mode;

    wire [31:0] Result;
    wire        zero;


    alu_ai dut (
        .A(A),
        .B(B),
        .C(C),
        .alu_en(alu_en),
        .alucontrol(alucontrol),
        .mode(mode),
        .Result(Result),
        .zero(zero)
    );


    initial begin
        $dumpfile("alu_ai_enable.vcd");
        $dumpvars(0, tb_alu_ai_enable);
    end


    initial begin

        A = 0;
        B = 0;
        C = 0;

        alu_en = 0;
        alucontrol = 0;
        mode = 0;

        #10;


        //================================================
        // ALU DISABLED
        // Inputs change while isolated
        //================================================

        alu_en = 0;

        mode = 2'b01;
        alucontrol = 5'b00000;

        A = 32'h11111111;
        B = 32'h22222222;
        #10;

        A = 32'hAAAAAAAA;
        B = 32'h55555555;
        #10;

        A = 32'hFFFFFFFF;
        B = 32'h12345678;
        #10;


        //================================================
        // ENABLE ALU
        //================================================

        alu_en = 1'b1;


        //================================================
        // Scalar ADD
        //================================================

        mode = 2'b01;

        A = 32'd100;
        B = 32'd25;
        alucontrol = 5'b00000;

        #10;


        // SUB

        A = 32'd100;
        B = 32'd25;
        alucontrol = 5'b00001;

        #10;


        // XOR

        A = 32'h12345678;
        B = 32'h87654321;
        alucontrol = 5'b00110;

        #10;


        // MUL

        A = 32'd12;
        B = 32'd10;
        alucontrol = 5'b11111;

        #10;


        //================================================
        // AI: VADD8
        //================================================

        A = 32'h01020304;
        B = 32'h05060708;

        alucontrol = 5'b10111;

        #10;


        //================================================
        // AI: VMAX8
        //================================================

        A = 32'h7F80F00A;
        B = 32'h0100F505;

        alucontrol = 5'b11000;

        #10;


        //================================================
        // AI: SDOTP4
        //================================================

        A = 32'h04030201;
        B = 32'h08070605;

        alucontrol = 5'b11101;

        #10;


        //================================================
        // AI: VRELU8
        //================================================

        mode = 2'b10;

        A = 32'h32EC0AFF;

        alucontrol = 5'b10110;

        #10;


        //================================================
        // R4 MAC
        //================================================

        mode = 2'b00;

        A = 32'd10;
        B = 32'd20;
        C = 32'd5;

        alucontrol = 5'b01110;

        #10;


        //================================================
        // I TYPE
        //================================================

        mode = 2'b11;

        A = 32'd100;
        C = 32'd20;

        alucontrol = 5'b00000;

        #10;


        //================================================
        // DISABLE AGAIN
        // Create switching on inputs
        //================================================

        alu_en = 0;

        mode = 2'b01;
        alucontrol = 5'b11101;

        A = 32'hAAAAAAAA;
        B = 32'h55555555;
        C = 32'hFFFFFFFF;

        #10;

        A = 32'h12345678;
        B = 32'h87654321;
        C = 32'h11111111;

        #10;

        A = 32'hFFFFFFFF;
        B = 32'h00000000;
        C = 32'h55555555;

        #20;


        $finish;

    end

endmodule
